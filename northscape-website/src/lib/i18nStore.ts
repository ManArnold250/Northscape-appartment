import { useState, useEffect } from "react";

export type LanguageCode = "en" | "rw" | "fr" | "sw" | "de" | "es" | "zh";

export interface LanguageOption {
  code: LanguageCode;
  name: string;
  shortName: string;
  nativeName: string;
  flag: string;
}

